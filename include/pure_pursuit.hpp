#pragma once

#include <vector>
#include <string>
#include <cmath>
#include <algorithm>

namespace vehicle_sim {

/**
 * @brief 2D vehicle pose representation for path tracking.
 */
struct Pose2D {
    double x = 0.0;       // Lateral position (meters, positive = right)
    double z = 0.0;       // Longitudinal position (meters, positive = forward)
    double heading = 0.0; // Vehicle heading in radians (0 = aligned with +Z forward, positive = counterclockwise / left)
    double velocity = 0.0;// Longitudinal velocity (m/s)
};

/**
 * @brief Waypoint definition for path/route representation.
 */
struct Waypoint {
    double x = 0.0;       // Lateral coordinate (meters)
    double z = 0.0;       // Longitudinal coordinate (meters)
    double target_speed = 10.0; // Optional target speed at waypoint (m/s)
};

/**
 * @brief Configuration parameters for Pure Pursuit controller.
 */
struct PurePursuitConfig {
    double wheelbase = 2.5;             // Vehicle wheelbase (meters)
    double lookahead_distance = 3.0;    // Lookahead distance L_d (meters)
    double max_steering_angle = 0.523599; // Maximum steering angle delta_max (~30 degrees in radians)
    double arrival_tolerance = 1.5;     // Distance tolerance to declare final waypoint arrival (meters)
    double min_lookahead_distance = 1.0;// Minimum lookahead distance
};

/**
 * @brief Output generated by the Pure Pursuit steering controller.
 */
struct SteeringOutput {
    double steering_command = 0.0;      // Normalized steering command in range [-1.0, 1.0]
    double steering_angle = 0.0;        // Computed steering angle in radians [-max_steering_angle, max_steering_angle]
    bool valid = true;                  // Validity flag
    bool fault_detected = false;        // Fault or invalidity indicator
    std::string fault_reason = "";      // Description of fault if invalid/faulted
    bool route_completed = false;       // True if final waypoint has been reached within arrival tolerance
    size_t target_waypoint_index = 0;   // Current target waypoint index in route
    double cross_track_error = 0.0;     // Current cross-track error to nearest path segment (meters)
};

/**
 * @brief Portable C++17 Pure Pursuit path tracking steering controller.
 * 
 * Coordinate Conventions & Sign Standards:
 * - Coordinate Frame: Cartesian X-Z plane where Z is forward (longitudinal) and X is right (lateral).
 * - Heading (theta): Angle in radians measured from the positive Z-axis. Positive heading rotates counterclockwise (turning left).
 * - Steering Angle (delta): Angle of front wheels in radians. Positive steering angle (delta > 0) turns the vehicle to the left (counterclockwise curvature).
 * - Normalized Steering Command (u_steer): Bounded output in [-1.0, 1.0], where +1.0 represents full left steering (+max_steering_angle),
 *   -1.0 represents full right steering (-max_steering_angle), and 0.0 represents straight ahead.
 */
class PurePursuitController {
public:
    explicit PurePursuitController(const PurePursuitConfig& config = PurePursuitConfig());

    /**
     * @brief Computes steering command and steering angle to track a sequence of waypoints.
     * @param ego_pose Current 2D vehicle pose (x, z, heading, velocity).
     * @param waypoints Ordered list of Waypoints defining the route.
     * @return SteeringOutput containing normalized steering command, steering angle, status, and telemetry.
     */
    SteeringOutput computeSteering(const Pose2D& ego_pose, const std::vector<Waypoint>& waypoints);

    /**
     * @brief Updates controller configuration.
     */
    void setConfig(const PurePursuitConfig& config);

    /**
     * @brief Gets current controller configuration.
     */
    const PurePursuitConfig& getConfig() const;

    /**
     * @brief Resets internal state (e.g. waypoint progression index).
     */
    void reset();

private:
    PurePursuitConfig config_;
    size_t current_target_index_ = 0;

    bool validateInputs(const Pose2D& pose, const std::vector<Waypoint>& waypoints) const;
    double computeCrossTrackError(const Pose2D& pose, const std::vector<Waypoint>& waypoints, size_t& nearest_seg_idx) const;
};

} // namespace vehicle_sim
